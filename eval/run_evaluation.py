"""Run the RAG against the evaluation questions and save raw outputs.

Run this file from the project root, where the existing `src/` package lives:

    python eval/run_evaluation.py

This stage intentionally does NOT calculate Ragas metrics yet.
It captures:
- question
- ground_truth
- answer generated by the existing RAG
- retrieved contexts
- source/page metadata when available
"""

import json
import os
import sys
from pathlib import Path

# Make project-root imports such as `from src...` work when this file is run directly.
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.conversation import get_conversation

from dataset import EVAL_DATASET


def serialize_document(doc):
    """Convert a LangChain Document into JSON-safe evaluation context."""
    metadata = getattr(doc, "metadata", {}) or {}
    return {
        "page_content": getattr(doc, "page_content", ""),
        "metadata": {
            "source": metadata.get("source"),
            "page": metadata.get("page"),
        },
    }


def main():
    output_dir = Path(__file__).resolve().parent / "results"
    output_dir.mkdir(parents=True, exist_ok=True)
    output_file = output_dir / "raw_results.json"

    conversation = get_conversation()
    results = []

    for item in EVAL_DATASET:
        print(f"[{item['id']}/{len(EVAL_DATASET)}] {item['question']}")

        # A unique session prevents one evaluation question's chat history
        # from influencing another question.
        session_id = f"eval_{item['id']}"

        response = conversation.invoke(
            {"input": item["question"]},
            config={"configurable": {"session_id": session_id}},
        )

        answer = response.get("answer", "")
        documents = response.get("context", []) or []

        results.append(
            {
                "id": item["id"],
                "question": item["question"],
                "ground_truth": item["ground_truth"],
                "answer": answer,
                "contexts": [serialize_document(doc) for doc in documents],
            }
        )

    output_file.write_text(
        json.dumps(results, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    print(f"\nSaved evaluation data to: {output_file}")


if __name__ == "__main__":
    main()
